DROP TYPE IF EXISTS ruolo_enum;

-- =================================================================
-- 1. Tipi ENUM e Creazione Tabelle
-- =================================================================

-- Creazione di un tipo ENUM personalizzato per i ruoli.
CREATE TYPE ruolo_enum AS ENUM ('ADMIN', 'USER');

-- Creazione della tabella 'users' (versione finale consolidata)
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) UNIQUE,
    first_name VARCHAR(255),
    last_name VARCHAR(255),
    password VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    birth_date DATE,
    role ruolo_enum NOT NULL,
    state BOOLEAN NOT NULL DEFAULT true,
    credits INTEGER NOT NULL DEFAULT 0
);

-- Creazione della tabella 'classrooms' (versione finale consolidata)
CREATE TABLE classrooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    link VARCHAR(255),
    max_seats INTEGER DEFAULT 10,
    is_active BOOLEAN DEFAULT true,
    date DATE,
    time TIME,
    duration INTEGER -- Durata in minuti
);

-- Creazione della tabella 'inscriptions' per collegare utenti e aule
CREATE TABLE inscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    classroom_id BIGINT NOT NULL,
    inscription_date TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
	registration BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT fk_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_classroom FOREIGN KEY(classroom_id) REFERENCES classrooms(id) ON DELETE CASCADE,
    -- Impedisce a un utente di iscriversi due volte alla stessa classe
    UNIQUE (user_id, classroom_id)
);

-- Creazione della tabella 'documents' con validazione Base64
CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    content TEXT,
    CONSTRAINT fk_owner FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
    -- Questo CHECK constraint valida che il contenuto sia una stringa Base64 valida.
    -- Tenterà di inserire una stringa non valida genererà un errore.
    CONSTRAINT content_is_base64 CHECK (content ~* '^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$')
);

